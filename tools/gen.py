def gen_bngapi():
    sheet = load("bng_api")
    L = [HEADER_LUA.format(sheet="bng_api"), """-- Each row is one wrapper. GE rows run in pcall; the first failure of each row is logged as
-- 'bngapi FAIL <id>' and the row's fallback is returned. Vehicle rows (M.ve.*) return a code string
-- for veh:queueLuaCommand that runs the body in pcall inside the vehicle VM.
local M = {}
M.ve = {}
M.failed = {}
M.ok = {}

local function logFail(id, err)
  if not M.failed[id] then
    M.failed[id] = tostring(err)
    if log then log('E', 'beamls.bngapi', 'bngapi FAIL ' .. id .. ': ' .. tostring(err)) end
  end
end

local function ser(v)
  local t = type(v)
  if t == 'number' then return string.format('%.17g', v) end
  if t == 'boolean' then return v and 'true' or 'false' end
  if t == 'nil' then return 'nil' end
  return string.format('%q', tostring(v))
end
M.ser = ser

function M.report()
  local ok, failed = {}, {}
  for id in pairs(M.ok) do ok[#ok + 1] = id end
  for id, err in pairs(M.failed) do failed[#failed + 1] = id .. ': ' .. err end
  table.sort(ok)
  table.sort(failed)
  return ok, failed
end

"""]
    for r in sheet["rows"]:
        args = r.get("args", [])
        arglist = ", ".join(args)
        body = "\n".join("    " + line for line in r["body"].split("\n"))
        L.append(f"-- {r['id']}: {r['purpose']} (source: {r['source']})\n")
        if r["vm"] == "ge":
            L.append(f"function M.{r['id']}({arglist})\n")
            L.append("  local res = {pcall(function()\n" + body + "\n  end)}\n")
            L.append(f"  if not res[1] then\n    logFail({lua_str(r['id'])}, res[2])\n    return {r['fallback']}\n  end\n")
            L.append(f"  M.ok[{lua_str(r['id'])}] = true\n  return unpack(res, 2, table.maxn(res))\nend\n\n")
        else:
            decl = "".join(f"'local {a} = ' .. ser({a}) .. '\\n' .. " for a in args)
            code = r["body"].replace("\\", "\\\\")
            L.append(f"function M.ve.{r['id']}({arglist})\n")
            L.append(f"  return 'local ok, err = pcall(function()\\n' .. {decl}{lua_str(code)} .. "
                     f"'\\nend)\\nif not ok then log(\"E\", \"beamls.ve\", \"bngapi FAIL {r['id']}: \" .. tostring(err)) end'\n")
            L.append("end\n\n")
    L.append("return M\n")
    write(os.path.join(BNG_GEN, "bngapi.lua"), "".join(L))


