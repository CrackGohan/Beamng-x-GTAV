CPP_TYPES = {
    "void": "void", "BOOL": "BOOL", "int": "int", "float": "float", "Hash": "Hash", "Any": "Any",
    "Ped": "Ped", "Vehicle": "Vehicle", "Entity": "Entity", "Player": "Player", "Object": "Object",
    "Cam": "Cam", "Vector3": "Vector3", "const char*": "const char*", "char*": "const char*",
}


def cpp_type(t):
    t = t.strip()
    if t in CPP_TYPES:
        return CPP_TYPES[t]
    if t.endswith("*"):
        base = t[:-1].strip()
        if base in CPP_TYPES:
            return CPP_TYPES[base] + "*"
    raise ValueError(f"unknown native type {t}")


def gen_natives():
    sheet = load("natives")
    games = {g["id"]: g for g in load("games")["rows"]}
    builds = games["gta-v"]["supported_builds"]
    by_ns = {}
    for r in sheet["rows"]:
        by_ns.setdefault(r["ns"], []).append(r)
    out = [HEADER_CPP.format(sheet="natives"), "#pragma once\n#include \"../core/invoker.hpp\"\n\n"]
    out.append("// One wrapper per row of sheets/natives.json: original hash, translated per build by the invoker.\n")
    for ns in sorted(by_ns):
        out.append(f"namespace {ns}\n{{\n")
        for r in by_ns[ns]:
            ret = cpp_type(r["ret"])
            params = []
            names = []
            for p in r["params"]:
                t, n = p.rsplit(" ", 1)
                params.append(f"{cpp_type(t)} {n}")
                names.append(n)
            args = "".join(", " + n for n in names)
            body = f"beamls::invoke<{ret}>(0x{int(r['hash'], 16):016X}ull{args})"
            if ret == "void":
                out.append(f"\tinline void {r['id']}({', '.join(params)}) {{ {body}; }}\n")
            else:
                out.append(f"\tinline {ret} {r['id']}({', '.join(params)}) {{ return {body}; }}\n")
        out.append("}\n\n")
    write(os.path.join(GTA_GEN, "natives.hpp"), "".join(out))

    x = [HEADER_CPP.format(sheet="natives"), "#pragma once\n#include <cstddef>\n#include <cstdint>\n\nnamespace beamls::gen\n{\n"]
    x.append("\tstruct XmapEntry { std::uint64_t original; std::uint64_t translated; const char* name; };\n")
    x.append("\tstruct BuildTable { const char* build; const XmapEntry* entries; std::size_t count; };\n\n")
    for b in builds:
        x.append(f"\t// Build {b}: translated == 0 means the cell is still empty in the sheet; the build cannot run.\n")
        x.append(f"\tinline constexpr XmapEntry kXmap_{b}[] = {{\n")
        for r in sheet["rows"]:
            t = r["xmap"].get(b, "") or "0x0"
            x.append(f"\t\t{{0x{int(r['hash'], 16):016X}ull, 0x{int(t, 16):016X}ull, \"{r['id']}\"}},\n")
        x.append("\t};\n\n")
    x.append("\tinline constexpr BuildTable kBuildTables[] = {\n")
    for b in builds:
        x.append(f"\t\t{{\"{b}\", kXmap_{b}, sizeof(kXmap_{b}) / sizeof(kXmap_{b}[0])}},\n")
    x.append("\t};\n}\n")
    write(os.path.join(GTA_GEN, "xmap.hpp"), "".join(x))


