def gen_bng_assets():
    """beamls_proxy jbeam (rigid invisible box sized by .pc variables) and the slab unit cube."""
    tp = load("traffic_proxies")["rows"]
    settings = {r["id"]: r["value"] for r in load("settings")["rows"]}
    medium = next((r for r in tp if r["id"] == "medium"), tp[0])
    corners = {}
    for sx in (-1, 1):
        for sy in (-1, 1):
            for sz in (-1, 1):
                name = "c" + "".join("p" if s > 0 else "n" for s in (sx, sy, sz))
                corners[name] = (sx, sy, sz)

    def expr(axis, s):
        var = {"x": "$width", "y": "$length", "z": "$height"}[axis]
        return f"$={'' if s > 0 else '-'}{var}/2"

    nodes = [["id", "posX", "posY", "posZ"], {"nodeWeight": "$=$mass/12"}, {"collision": True},
             {"selfCollision": False}, {"frictionCoef": 0.6}, {"nodeMaterial": "|NM_METAL"}, {"group": "beamls_proxy"}]
    nodes.append(["p0", 0.0, 0.0, 0.0])
    nodes.append(["pb", 0.0, "$=$length/2", 0.0])   # back: BeamNG vehicles face -Y
    nodes.append(["pl", "$=$width/2", 0.0, 0.0])    # left: +X
    nodes.append(["pu", 0.0, 0.0, "$=$height/2"])
    for n, (sx, sy, sz) in corners.items():
        nodes.append([n, expr("x", sx), expr("y", sy), expr("z", sz)])
    names = [n[0] for n in nodes if isinstance(n, list) and n[0] != "id"]
    beams = [["id1:", "id2:"], {"beamSpring": 30000000, "beamDamp": 800}, {"beamDeform": "FLT_MAX", "beamStrength": "FLT_MAX"}]
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            beams.append([names[i], names[j]])
    # Box faces as outward-facing triangles (counter-clockwise seen from outside).
    tris = [["id1:", "id2:", "id3:"]]
    faces = []
    for axis in range(3):
        for s in (-1, 1):
            quad = [n for n, c in corners.items() if c[axis] == s]
            others = [a for a in range(3) if a != axis]
            # order the 4 corners around the face
            quad.sort(key=lambda n: __import__("math").atan2(corners[n][others[1]], corners[n][others[0]]))
            normal = [0, 0, 0]
            normal[axis] = s
            a, b, c = (corners[q] for q in quad[:3])
            u = [b[k] - a[k] for k in range(3)]
            v = [c[k] - a[k] for k in range(3)]
            cr = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
            if sum(cr[k] * normal[k] for k in range(3)) < 0:
                quad.reverse()
            faces.append(quad)
    for q in faces:
        tris.append([q[0], q[1], q[2]])
        tris.append([q[0], q[2], q[3]])
    part = {
        "information": {"authors": "BeamNG x Los Santos", "name": "Traffic proxy body (invisible)"},
        "slotType": "main",
        "variables": [
            ["name", "type", "unit", "category", "default", "min", "max", "title", "description"],
            ["$length", "range", "m", "beamls", medium["length"], 1.0, 20.0, "Length", "Box length"],
            ["$width", "range", "m", "beamls", medium["width"], 0.5, 4.0, "Width", "Box width"],
            ["$height", "range", "m", "beamls", medium["height"], 0.5, 5.0, "Height", "Box height"],
            ["$mass", "range", "kg", "beamls", medium["mass_kg"], 50, 30000, "Mass", "Total mass"],
        ],
        "refNodes": [["ref:", "back:", "left:", "up:"], ["p0", "pb", "pl", "pu"]],
        "nodes": nodes,
        "beams": beams,
        "triangles": tris,
    }
    jbeam = {"beamls_proxy_body": part}
    header = "// GENERATED by tools/gen.py from sheets/traffic_proxies.json. Invisible rigid box: no flexbodies.\n"
    write(os.path.join(BNG_MOD, "vehicles", "beamls_proxy", "beamls_proxy.jbeam"), header + json.dumps(jbeam, indent=1) + "\n")
    write(os.path.join(BNG_MOD, "vehicles", "beamls_proxy", "info.json"), json.dumps({
        "Name": "BeamNG x Los Santos traffic proxy", "Brand": "BeamLS", "Type": "Prop", "Author": "BeamNG x Los Santos",
        "default_pc": medium["id"], "Description": "Invisible solid stand-in for a GTA V vehicle. Spawned by the mashup only."}, indent=2) + "\n")

    # Slab: unit cube centred on the origin, key-coloured unlit material so it vanishes in the composite
    # even if it is drawn.
    k = settings["key_color"]
    kc = " ".join(f"{c / 255:.4f}" for c in k)
    v = []
    for z in (-0.5, 0.5):
        for y in (-0.5, 0.5):
            for x in (-0.5, 0.5):
                v.append((x, y, z))
    idx = {p: i for i, p in enumerate(v)}
    quads = [((-0.5, -0.5, -0.5), (-0.5, 0.5, -0.5), (0.5, 0.5, -0.5), (0.5, -0.5, -0.5)),   # bottom
             ((-0.5, -0.5, 0.5), (0.5, -0.5, 0.5), (0.5, 0.5, 0.5), (-0.5, 0.5, 0.5)),       # top
             ((-0.5, -0.5, -0.5), (0.5, -0.5, -0.5), (0.5, -0.5, 0.5), (-0.5, -0.5, 0.5)),   # front
             ((-0.5, 0.5, -0.5), (-0.5, 0.5, 0.5), (0.5, 0.5, 0.5), (0.5, 0.5, -0.5)),       # back
             ((-0.5, -0.5, -0.5), (-0.5, -0.5, 0.5), (-0.5, 0.5, 0.5), (-0.5, 0.5, -0.5)),   # left
             ((0.5, -0.5, -0.5), (0.5, 0.5, -0.5), (0.5, 0.5, 0.5), (0.5, -0.5, 0.5))]       # right
    tri = []
    for q in quads:
        a, b, c, d = (idx[p] for p in q)
        tri += [a, b, c, a, c, d]
    pos = " ".join(f"{x} {y} {z}" for x, y, z in v)
    dae = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen.py: unit cube for BeamNG x Los Santos collision slabs -->
<COLLADA xmlns="http://www.collada.org/2005/11/COLLADASchema" version="1.4.1">
  <asset><unit name="meter" meter="1"/><up_axis>Z_UP</up_axis></asset>
  <library_effects><effect id="beamls_key-fx"><profile_COMMON><technique sid="common"><constant><emission><color>{kc} 1</color></emission></constant></technique></profile_COMMON></effect></library_effects>
  <library_materials><material id="beamls_key" name="beamls_key"><instance_effect url="#beamls_key-fx"/></material></library_materials>
  <library_geometries>
    <geometry id="slab-mesh" name="slab">
      <mesh>
        <source id="slab-pos"><float_array id="slab-pos-array" count="{len(v) * 3}">{pos}</float_array>
          <technique_common><accessor source="#slab-pos-array" count="{len(v)}" stride="3"><param name="X" type="float"/><param name="Y" type="float"/><param name="Z" type="float"/></accessor></technique_common></source>
        <vertices id="slab-vtx"><input semantic="POSITION" source="#slab-pos"/></vertices>
        <triangles material="beamls_key" count="{len(tri) // 3}"><input semantic="VERTEX" source="#slab-vtx" offset="0"/><p>{" ".join(str(i) for i in tri)}</p></triangles>
      </mesh>
    </geometry>
  </library_geometries>
  <library_visual_scenes><visual_scene id="Scene"><node id="slab" name="slab"><instance_geometry url="#slab-mesh"><bind_material><technique_common><instance_material symbol="beamls_key" target="#beamls_key"/></technique_common></bind_material></instance_geometry></node></visual_scene></library_visual_scenes>
  <scene><instance_visual_scene url="#Scene"/></scene>
</COLLADA>
"""
    write(os.path.join(BNG_MOD, "art", "shapes", "beamls", "slab.dae"), dae)
    mat = {"beamls_key": {"name": "beamls_key", "mapTo": "beamls_key", "class": "Material", "version": 1.5,
                          "Stages": [{"baseColorFactor": [k[0] / 255, k[1] / 255, k[2] / 255, 1.0],
                                      "emissiveFactor": [k[0] / 255, k[1] / 255, k[2] / 255]}, {}, {}, {}],
                          "castShadows": False, "translucent": False, "materialTag0": "beamls"}}
    write(os.path.join(BNG_MOD, "art", "shapes", "beamls", "main.materials.json"), json.dumps(mat, indent=2) + "\n")


