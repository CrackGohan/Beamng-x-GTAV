def cpp_const(name, v):
    if isinstance(v, bool):
        return f"\tinline constexpr bool {name} = {'true' if v else 'false'};\n"
    if isinstance(v, int):
        return f"\tinline constexpr int {name} = {v};\n"
    if isinstance(v, float):
        return f"\tinline constexpr float {name} = {v!r}f;\n"
    if isinstance(v, str):
        return f"\tinline constexpr const char* {name} = {json.dumps(v)};\n"
    if isinstance(v, list):
        if all(isinstance(x, str) for x in v):
            items = ", ".join(json.dumps(x) for x in v)
            return f"\tinline constexpr const char* {name}[] = {{{items}}};\n"
        if all(isinstance(x, int) and not isinstance(x, bool) for x in v):
            return f"\tinline constexpr int {name}[] = {{{', '.join(str(x) for x in v)}}};\n"
        return f"\tinline constexpr float {name}[] = {{{', '.join(repr(float(x)) + 'f' for x in v)}}};\n"
    raise TypeError(v)


def gen_settings():
    sheet = load("settings")
    c = [HEADER_CPP.format(sheet="settings"), "#pragma once\n\nnamespace beamls::settings\n{\n"]
    L = [HEADER_LUA.format(sheet="settings"), "local M = {}\n"]
