def gen_tables():
    keys = load("keys")
    c = [HEADER_CPP.format(sheet="keys"), "#pragma once\n\nnamespace beamls::gen\n{\n"]
    c.append("\tenum class KeyAction { " + ", ".join(camel(k["id"]) for k in keys["rows"] if k["side"] == "gta") + " };\n")
    c.append("\tstruct KeyRow { KeyAction action; bool isVk; int code; const char* label; };\n")
    c.append("\tinline constexpr KeyRow kKeys[] = {\n")
    for k in keys["rows"]:
        if k["side"] != "gta":
            continue
        kind, val = k["input"].split(":")
        c.append(f"\t\t{{KeyAction::{camel(k['id'])}, {'true' if kind == 'vk' else 'false'}, {int(val, 0)}, {json.dumps(k['label'])}}}, // {k['action']}\n")
    c.append("\t};\n}\n")
    write(os.path.join(GTA_GEN, "keys.hpp"), "".join(c))

    L = [HEADER_LUA.format(sheet="keys"), "local M = {}\n"]
    actions = {}
    for k in keys["rows"]:
        L.append(f"M[{lua_str(k['id'])}] = {{side = {lua_str(k['side'])}, input = {lua_str(k['input'])}, label = {lua_str(k['label'])}}}\n")
        if k["side"] == "beamng":
            actions["beamls_" + k["id"]] = {
                "cat": "beamls", "order": len(actions), "ctx": "tlua",
                "onDown": f"if beamls_main then beamls_main.onKey({json.dumps(k['id'])}) end",
                "title": "BeamNG x Los Santos: " + k["label"], "desc": k["action"],
            }
    L.append("return M\n")
    write(os.path.join(BNG_GEN, "keys.lua"), "".join(L))
    write(os.path.join(BNG_MOD, "lua", "ge", "extensions", "core", "input", "actions", "beamls.json"),
          json.dumps(actions, indent=2) + "\n")

    ctl = load("controls")
