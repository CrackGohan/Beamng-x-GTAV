CPP_FIELD = {"f32": "float", "i32": "std::int32_t", "u32": "std::uint32_t", "bool": "bool", "str": "std::string",
             "f32[]": "std::vector<float>"}
CPP_DEFAULT = {"f32": " = 0.0f", "i32": " = 0", "u32": " = 0", "bool": " = false", "str": "", "f32[]": ""}


def camel(s):
    return "".join(p.capitalize() for p in s.split("_"))


def cpp_encode_scalar(name, typ, expr):
    if typ == "f32":
        return f"w.num(\"{name}\", {expr});"
    if typ in ("i32", "u32"):
        return f"w.integer(\"{name}\", static_cast<long long>({expr}));"
    if typ == "bool":
        return f"w.boolean(\"{name}\", {expr});"
    if typ == "str":
        return f"w.str(\"{name}\", {expr});"
    if typ == "f32[]":
        return f"w.floats(\"{name}\", {expr});"
    raise ValueError(typ)


def cpp_decode_scalar(typ, src, dst):
    if typ == "f32":
        return f"{dst} = static_cast<float>({src}.num());"
    if typ == "i32":
        return f"{dst} = static_cast<std::int32_t>({src}.num());"
    if typ == "u32":
        return f"{dst} = static_cast<std::uint32_t>({src}.num());"
    if typ == "bool":
        return f"{dst} = {src}.boolean();"
    if typ == "str":
        return f"{dst} = {src}.str();"
    if typ == "f32[]":
        return f"{dst}.clear(); for (const auto& e : {src}.arr()) {dst}.push_back(static_cast<float>(e.num()));"
    raise ValueError(typ)


def gen_protocol():
    sheet = load("messages")
    proto = sheet["proto"]
    o = [HEADER_CPP.format(sheet="messages"), "#pragma once\n#include <cstdint>\n#include <string>\n#include <vector>\n#include \"../core/json.hpp\"\n\n"]
    o.append("namespace beamls::msg\n{\n")
    o.append(f"\tinline constexpr int kProto = {proto};\n\n")
    for m in sheet["rows"]:
        cname = camel(m["id"])
        o.append(f"\t// {m['id']} ({m['dir']}, {m['rate']}): {m['purpose']}\n")
        o.append(f"\tstruct {cname}\n\t{{\n\t\tstatic constexpr const char* kType = \"{m['id']}\";\n")
        for f in m["fields"]:
            name, typ = f[0], f[1]
            if typ == "rec[]":
                rname = camel(name.rstrip("s")) if name.endswith("s") else camel(name) + "Rec"
                o.append(f"\t\tstruct {rname}\n\t\t{{\n")
                for rf in f[3]:
                    o.append(f"\t\t\t{CPP_FIELD[rf[1]]} {rf[0]}{CPP_DEFAULT[rf[1]]}; // {rf[2]}\n")
                o.append("\t\t};\n")
                o.append(f"\t\tstd::vector<{rname}> {name}; // {f[2]}\n")
            else:
                o.append(f"\t\t{CPP_FIELD[typ]} {name}{CPP_DEFAULT[typ]}; // {f[2]}\n")
        # encode
        o.append("\n\t\tstd::string encode() const\n\t\t{\n\t\t\tjson::Writer w;\n\t\t\tw.begin();\n\t\t\tw.str(\"t\", kType);\n")
        for f in m["fields"]:
            name, typ = f[0], f[1]
            if typ == "rec[]":
                o.append(f"\t\t\tw.beginArray(\"{name}\");\n\t\t\tfor (const auto& r : {name})\n\t\t\t{{\n\t\t\t\tw.beginRow();\n")
                for rf in f[3]:
                    if rf[1] == "f32":
                        o.append(f"\t\t\t\tw.rowNum(r.{rf[0]});\n")
                    elif rf[1] in ("i32", "u32"):
                        o.append(f"\t\t\t\tw.rowInt(static_cast<long long>(r.{rf[0]}));\n")
                    else:
                        raise ValueError("rec fields must be numeric")
                o.append("\t\t\t\tw.endRow();\n\t\t\t}\n\t\t\tw.endArray();\n")
            else:
                o.append(f"\t\t\t{cpp_encode_scalar(name, typ, name)}\n")
        o.append("\t\t\tw.end();\n\t\t\treturn w.take();\n\t\t}\n")
        # decode
        o.append("\n\t\tbool decode(const json::Value& v)\n\t\t{\n\t\t\tif (!v.isObject()) return false;\n")
        for f in m["fields"]:
            name, typ = f[0], f[1]
            if typ == "rec[]":
                o.append(f"\t\t\t{name}.clear();\n\t\t\tif (const json::Value* a = v.get(\"{name}\"))\n\t\t\t{{\n\t\t\t\tfor (const auto& row : a->arr())\n\t\t\t\t{{\n")
                o.append(f"\t\t\t\t\tconst auto& c = row.arr();\n\t\t\t\t\tif (c.size() < {len(f[3])}) continue;\n\t\t\t\t\t{name}.emplace_back();\n\t\t\t\t\tauto& r = {name}.back();\n")
                for i, rf in enumerate(f[3]):
                    o.append(f"\t\t\t\t\t{cpp_decode_scalar(rf[1], f'c[{i}]', 'r.' + rf[0])}\n")
                o.append("\t\t\t\t}\n\t\t\t}\n")
            else:
                o.append(f"\t\t\tif (const json::Value* f = v.get(\"{name}\")) {{ {cpp_decode_scalar(typ, '(*f)', name)} }}\n")
        o.append("\t\t\treturn true;\n\t\t}\n\t};\n\n")
    o.append("}\n")
    write(os.path.join(GTA_GEN, "protocol.hpp"), "".join(o))

    L = [HEADER_LUA.format(sheet="messages"), "local M = {}\n", f"M.proto = {proto}\nM.encode = {{}}\nM.decode = {{}}\nM.dir = {{}}\n\n"]
    for m in sheet["rows"]:
        L.append(f"-- {m['id']} ({m['dir']}): {m['purpose']}\nM.dir[{lua_str(m['id'])}] = {lua_str(m['dir'])}\n")
        L.append(f"M.encode[{lua_str(m['id'])}] = function(m)\n  local o = {{t = {lua_str(m['id'])}}}\n")
        for f in m["fields"]:
            name, typ = f[0], f[1]
            if typ == "rec[]":
                L.append(f"  o.{name} = {{}}\n  for i, r in ipairs(m.{name} or {{}}) do\n    o.{name}[i] = {{")
                L.append(", ".join(f"r.{rf[0]} or 0" for rf in f[3]))
                L.append("}\n  end\n")
            elif typ == "f32[]":
                L.append(f"  o.{name} = m.{name} or {{}}\n")
            elif typ == "bool":
                L.append(f"  o.{name} = m.{name} and true or false\n")
            elif typ == "str":
                L.append(f"  o.{name} = tostring(m.{name} or '')\n")
            else:
                L.append(f"  o.{name} = tonumber(m.{name}) or 0\n")
        L.append("  return o\nend\n")
        L.append(f"M.decode[{lua_str(m['id'])}] = function(o)\n  local m = {{t = {lua_str(m['id'])}}}\n")
        for f in m["fields"]:
            name, typ = f[0], f[1]
            if typ == "rec[]":
                L.append(f"  m.{name} = {{}}\n  for i, c in ipairs(o.{name} or {{}}) do\n    m.{name}[i] = {{")
                L.append(", ".join(f"{rf[0]} = c[{i + 1}]" for i, rf in enumerate(f[3])))
                L.append("}\n  end\n")
            elif typ == "f32[]":
                L.append(f"  m.{name} = o.{name} or {{}}\n")
            elif typ == "bool":
                L.append(f"  m.{name} = o.{name} == true\n")
            elif typ == "str":
                L.append(f"  m.{name} = o.{name} and tostring(o.{name}) or ''\n")
            else:
                L.append(f"  m.{name} = tonumber(o.{name}) or 0\n")
        L.append("  return m\nend\n\n")
    L.append("return M\n")
    write(os.path.join(BNG_GEN, "protocol.lua"), "".join(L))


