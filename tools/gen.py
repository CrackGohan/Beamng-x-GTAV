#!/usr/bin/env python3
"""Generate code from the sheets. Every row becomes one piece of code built from its columns.

  python3 tools/gen.py

GTA side (C++17, gta/src/gen/):        natives.hpp, xmap.hpp, protocol.hpp, settings.hpp, keys.hpp,
                                       controls.hpp, obstacles.hpp, player_proxies.hpp, garages.hpp
BeamNG side (Lua, .../beamls/gen/):    protocol.lua, settings.lua, bngapi.lua, obstacles.lua,
                                       traffic_proxies.lua, keys.lua
BeamNG data:                           core/input/actions/beamls.json, vehicles/beamls_proxy/*.pc
Docs:                                  CREDITS.md

Never edit generated files by hand: change the sheet and run this again.
"""
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEETS = os.path.join(ROOT, "sheets")
GTA_GEN = os.path.join(ROOT, "gta", "src", "gen")
BNG_MOD = os.path.join(ROOT, "beamng", "mod")
BNG_GEN = os.path.join(BNG_MOD, "lua", "ge", "extensions", "beamls", "gen")
HEADER_CPP = "// GENERATED by tools/gen.py from sheets/{sheet}.json. Do not edit; change the sheet.\n"
HEADER_LUA = "-- GENERATED by tools/gen.py from sheets/{sheet}.json. Do not edit; change the sheet.\n"


def load(name):
    with open(os.path.join(SHEETS, name + ".json"), encoding="utf-8") as f:
        return json.load(f)


def digest():
    h = hashlib.sha256()
    for name in sorted(os.listdir(SHEETS)):
        if name.endswith(".json"):
            with open(os.path.join(SHEETS, name), "rb") as f:
                h.update(name.encode())
                h.update(f.read())
    return h.hexdigest()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def joaat(s):
    h = 0
    for c in s.lower().encode():
        h = (h + c) & 0xFFFFFFFF
        h = (h + (h << 10)) & 0xFFFFFFFF
        h ^= h >> 6
    h = (h + (h << 3)) & 0xFFFFFFFF
    h ^= h >> 11
    h = (h + (h << 15)) & 0xFFFFFFFF
    return h


def lua_str(s):
    return json.dumps(s)  # JSON string escapes are valid Lua string escapes for our content


def lua_val(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, list):
        return "{" + ", ".join(lua_val(x) for x in v) + "}"
    if v is None:
        return "nil"
    raise TypeError(v)


